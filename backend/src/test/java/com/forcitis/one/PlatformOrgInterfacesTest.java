package com.forcitis.one;

import static org.assertj.core.api.Assertions.assertThat;

import com.tngtech.archunit.core.domain.Dependency;
import com.tngtech.archunit.core.domain.JavaClass;
import java.io.IOException;
import java.lang.reflect.Constructor;
import java.lang.reflect.Method;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.HashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import java.util.Set;
import java.util.TreeSet;
import java.util.stream.Collectors;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.modulith.NamedInterface;

class PlatformOrgInterfacesTest {
    static final Path LIST = Path.of("architecture/platform-org-interfaces.txt");
    static final Path SNAPSHOT = Path.of("architecture/platform-org-interfaces.signatures.txt");
    static final String ROOT = ArchitectureRulesTest.ROOT + ".";

    record Entry(String platformModule, String organizationModule, String interfaceName) {
        String key() {
            return platformModule + " -> " + organizationModule + "::" + interfaceName;
        }
    }

    @Test
    @DisplayName("ADR-0066 decision 1 item 3: a platform module uses organization code only through a listed NamedInterface")
    void platformUsesOnlyListedOrganizationInterfaces() throws IOException {
        assertThat(usageViolations(read(), ArchitectureRulesTest.CLASSES)).isEmpty();
    }

    @Test
    @DisplayName("every listed interface exists with @NamedInterface, is on an edge of module-dependencies.txt and is used")
    void listedInterfacesExistAndAreUsed() throws IOException {
        assertThat(listViolations(read(), moduleEdges(), ArchitectureRulesTest.CLASSES)).isEmpty();
    }

    @Test
    @DisplayName("counterexamples: an empty list reports every existing use, a list entry without an edge or interface is reported")
    void violationsAreReported() throws IOException {
        List<Entry> actual = read();
        assertThat(usageViolations(List.of(), ArchitectureRulesTest.CLASSES))
                .anyMatch(v -> v.startsWith("platform.approval -> organization.workforce::api"))
                .anyMatch(v -> v.startsWith("platform.identity -> organization.workforce::events"));
        assertThat(usageViolations(actual.stream().filter(e -> !e.interfaceName().equals("events")).toList(), ArchitectureRulesTest.CLASSES))
                .anyMatch(v -> v.startsWith("platform.identity -> organization.workforce::events"));
        List<Entry> broken = new ArrayList<>(actual);
        broken.add(new Entry("platform.audit", "organization.workforce", "api"));
        broken.add(new Entry("platform.approval", "organization.workforce", "nothing"));
        assertThat(listViolations(broken, moduleEdges(), ArchitectureRulesTest.CLASSES)).anyMatch(v -> v.contains("platform.audit -> organization.workforce::api") && v.contains("module-dependencies.txt"))
                .anyMatch(v -> v.contains("organization.workforce::nothing") && v.contains("@NamedInterface"));
    }

    @Test
    @DisplayName("the public signatures of the listed interfaces equal platform-org-interfaces.signatures.txt (a change needs 已通知平台 owner in the pull request)")
    void signaturesEqualTheSnapshot() throws Exception {
        List<String> actual = signatures(read());
        if (Boolean.getBoolean("org.interfaces.update")) {
            Files.write(SNAPSHOT, (header() + String.join("\n", actual) + "\n").getBytes(java.nio.charset.StandardCharsets.UTF_8));
            return;
        }
        List<String> pinned = Files.readAllLines(SNAPSHOT).stream().filter(l -> !l.isBlank() && !l.startsWith("#")).toList();
        Set<String> added = new TreeSet<>(actual);
        pinned.forEach(added::remove);
        Set<String> removed = new TreeSet<>(pinned);
        actual.forEach(removed::remove);
        assertThat(added).as("signatures new or changed since the snapshot (regenerate with -Dorg.interfaces.update=true and write 已通知平台 owner in the pull request)").isEmpty();
        assertThat(removed).as("signatures gone or changed since the snapshot (regenerate with -Dorg.interfaces.update=true and write 已通知平台 owner in the pull request)").isEmpty();
    }

    static String header() {
        return "# Public signatures of the organization interfaces listed in platform-org-interfaces.txt; generated by PlatformOrgInterfacesTest (-Dorg.interfaces.update=true), do not edit by hand.\n"
                + "# A change here means the platform owner must be told: the pull request body has to contain 已通知平台 owner (scripts/ci/org_interface_notice.py).\n";
    }

    static List<Entry> read() throws IOException {
        List<Entry> entries = new ArrayList<>();
        for (String raw : Files.readAllLines(LIST)) {
            String line = raw.contains("#") ? raw.substring(0, raw.indexOf('#')) : raw;
            if (line.isBlank()) {
                continue;
            }
            String[] sides = line.split("->", -1);
            String[] target = sides[1].trim().split("::", -1);
            if (sides.length != 2 || target.length != 2) {
                throw new AssertionError("platform-org-interfaces.txt line not of the form <platform module> -> <organization module>::<interface>: " + raw);
            }
            entries.add(new Entry(sides[0].trim(), target[0].trim(), target[1].trim()));
        }
        return entries;
    }

    static Map<String, Set<String>> moduleEdges() throws IOException {
        Map<String, Set<String>> edges = new HashMap<>();
        for (String line : Files.readAllLines(Path.of("architecture/module-dependencies.txt"))) {
            if (line.isBlank() || line.startsWith("#")) {
                continue;
            }
            String[] parts = line.split("->", -1);
            edges.put(parts[0].trim(), Arrays.stream(parts[1].split(",")).map(String::trim).filter(s -> !s.isEmpty()).collect(Collectors.toSet()));
        }
        return edges;
    }

    static Set<String> usageViolations(List<Entry> entries, Iterable<JavaClass> classes) {
        Set<String> allowed = entries.stream().map(Entry::key).collect(Collectors.toSet());
        Set<String> violations = new TreeSet<>();
        for (JavaClass c : classes) {
            Optional<String> from = ModuleDependencyTest.moduleOf(c);
            if (from.isEmpty() || !from.get().startsWith("platform.")) {
                continue;
            }
            for (Dependency d : c.getDirectDependenciesFromSelf()) {
                Optional<String> to = ModuleDependencyTest.moduleOf(d.getTargetClass());
                if (to.isEmpty() || !to.get().startsWith("organization.")) {
                    continue;
                }
                String name = interfaceNameOf(d.getTargetClass());
                String key = from.get() + " -> " + to.get() + "::" + (name == null ? "(not a NamedInterface)" : name);
                if (name == null || !allowed.contains(key)) {
                    violations.add(key + " (" + c.getSimpleName() + " uses " + d.getTargetClass().getSimpleName() + ")");
                }
            }
        }
        return violations;
    }

    static Set<String> listViolations(List<Entry> entries, Map<String, Set<String>> edges, Iterable<JavaClass> classes) {
        Set<String> violations = new TreeSet<>();
        Set<String> used = new LinkedHashSet<>();
        Set<String> declared = new LinkedHashSet<>();
        for (JavaClass c : classes) {
            Optional<String> module = ModuleDependencyTest.moduleOf(c);
            if (module.isPresent() && module.get().startsWith("organization.")) {
                String name = interfaceNameOf(c);
                if (name != null) {
                    declared.add(module.get() + "::" + name);
                }
            }
            Optional<String> from = module.filter(m -> m.startsWith("platform."));
            if (from.isPresent()) {
                for (Dependency d : c.getDirectDependenciesFromSelf()) {
                    Optional<String> to = ModuleDependencyTest.moduleOf(d.getTargetClass());
                    String name = interfaceNameOf(d.getTargetClass());
                    if (to.isPresent() && to.get().startsWith("organization.") && name != null) {
                        used.add(from.get() + " -> " + to.get() + "::" + name);
                    }
                }
            }
        }
        for (Entry e : entries) {
            if (!e.platformModule().startsWith("platform.") || !e.organizationModule().startsWith("organization.")) {
                violations.add(e.key() + ": left side must be a platform module and right side an organization module");
            }
            if (!edges.getOrDefault(e.platformModule(), Set.of()).contains(e.organizationModule())) {
                violations.add(e.key() + ": no such edge in architecture/module-dependencies.txt");
            }
            if (!declared.contains(e.organizationModule() + "::" + e.interfaceName())) {
                violations.add(e.key() + ": " + e.organizationModule() + " has no @NamedInterface(\"" + e.interfaceName() + "\")");
            }
            if (!used.contains(e.key())) {
                violations.add(e.key() + ": listed but not used by any class (remove the line, or list it with the code that uses it)");
            }
        }
        return violations;
    }

    static String interfaceNameOf(JavaClass target) {
        try {
            Package pkg = Class.forName(target.getName()).getPackage();
            NamedInterface annotation = pkg == null ? null : pkg.getAnnotation(NamedInterface.class);
            return annotation == null ? null : annotation.value()[0];
        } catch (ClassNotFoundException e) {
            throw new AssertionError(e);
        }
    }

    static List<String> signatures(List<Entry> entries) throws Exception {
        List<String> lines = new ArrayList<>();
        for (Entry e : entries) {
            if (!e.organizationModule().startsWith("organization.")) {
                continue;
            }
            for (JavaClass c : ArchitectureRulesTest.CLASSES) {
                if (ModuleDependencyTest.moduleOf(c).equals(Optional.of(e.organizationModule())) && interfaceNameOf(c) != null
                        && interfaceNameOf(c).equals(e.interfaceName()) && !c.getSimpleName().equals("package-info") && c.getEnclosingClass().isEmpty()) {
                    describe(Class.forName(c.getName()), e.organizationModule() + "::" + e.interfaceName(), lines);
                }
            }
        }
        return lines.stream().distinct().sorted().toList();
    }

    private static void describe(Class<?> type, String scope, List<String> lines) {
        String name = type.getName().replace(ROOT, "");
        lines.add(scope + " " + name + " " + type.toGenericString().replace(ROOT, ""));
        for (Constructor<?> k : type.getDeclaredConstructors()) {
            if (java.lang.reflect.Modifier.isPublic(k.getModifiers())) {
                lines.add(scope + " " + name + " " + k.toGenericString().replace(ROOT, ""));
            }
        }
        for (Method m : type.getDeclaredMethods()) {
            if (java.lang.reflect.Modifier.isPublic(m.getModifiers()) && !m.isSynthetic()) {
                lines.add(scope + " " + name + " " + m.toGenericString().replace(ROOT, ""));
            }
        }
        for (java.lang.reflect.Field f : type.getDeclaredFields()) {
            if (java.lang.reflect.Modifier.isPublic(f.getModifiers()) && !f.isSynthetic()) {
                lines.add(scope + " " + name + " " + f.toGenericString().replace(ROOT, ""));
            }
        }
        for (Class<?> nested : type.getDeclaredClasses()) {
            if (java.lang.reflect.Modifier.isPublic(nested.getModifiers())) {
                describe(nested, scope, lines);
            }
        }
    }
}
