package com.forcitis.one.platform.identity.application;

import com.forcitis.one.kernel.ErrorCode;

/**
 * Business errors of platform.identity (G48: {SUBDOMAIN}_{BC}_{REASON}). Login errors are deliberately coarse: a caller
 * learns "the credential is not acceptable", never which check failed; the precise reason goes to the audit trail.
 */
public enum IdentityError implements ErrorCode {
    PLATFORM_IDENTITY_CREDENTIALS_INVALID,
    PLATFORM_IDENTITY_NETWORK_DENIED,
    PLATFORM_IDENTITY_STATE_INVALID,
    PLATFORM_IDENTITY_WECOM_CODE_INVALID,
    PLATFORM_IDENTITY_WECOM_NOT_BOUND,
    PLATFORM_IDENTITY_TICKET_INVALID,
    PLATFORM_IDENTITY_TICKET_REPLAYED,
    PLATFORM_IDENTITY_SEEYON_UNAVAILABLE,
    PLATFORM_IDENTITY_LOGIN_NAME_UNKNOWN,
    PLATFORM_IDENTITY_ACCOUNT_DISABLED,
    PLATFORM_IDENTITY_EMPLOYEE_SEPARATED,
    PLATFORM_IDENTITY_ROLE_NOT_ALLOWED,
    PLATFORM_IDENTITY_ROLE_NOT_FOUND,
    PLATFORM_IDENTITY_ROLE_INVALID_CODE,
    PLATFORM_IDENTITY_ROLE_BLANK_NAME,
    PLATFORM_IDENTITY_ROLE_RESERVED_CODE,
    PLATFORM_IDENTITY_ROLE_DUPLICATE_CODE,
    PLATFORM_IDENTITY_ROLE_DUPLICATE_NAME,
    PLATFORM_IDENTITY_ROLE_SYSTEM_FROZEN,
    PLATFORM_IDENTITY_PERMISSION_UNKNOWN,
    PLATFORM_IDENTITY_ACCOUNT_NOT_FOUND
}
