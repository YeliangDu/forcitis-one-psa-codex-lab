package com.forcitis.one.platform.identity.api;

import com.forcitis.one.kernel.DomainException;
import com.forcitis.one.kernel.ErrorCode;
import com.forcitis.one.kernel.ErrorKind;

/** Login errors are coarse: the caller never learns which check failed; the audit trail has the reason. */
public enum IdentityError implements ErrorCode {
    PLATFORM_IDENTITY_CREDENTIALS_INVALID(ErrorKind.UNAUTHENTICATED),
    PLATFORM_IDENTITY_NETWORK_DENIED(ErrorKind.FORBIDDEN),
    PLATFORM_IDENTITY_STATE_INVALID(ErrorKind.UNAUTHENTICATED),
    PLATFORM_IDENTITY_WECOM_CODE_INVALID(ErrorKind.UNAUTHENTICATED),
    PLATFORM_IDENTITY_WECOM_NOT_BOUND(ErrorKind.UNAUTHENTICATED),
    PLATFORM_IDENTITY_TICKET_INVALID(ErrorKind.UNAUTHENTICATED),
    PLATFORM_IDENTITY_TICKET_REPLAYED(ErrorKind.UNAUTHENTICATED),
    PLATFORM_IDENTITY_SSO_UNAVAILABLE(ErrorKind.UNAVAILABLE),
    PLATFORM_IDENTITY_LOGIN_NAME_UNKNOWN(ErrorKind.UNAUTHENTICATED),
    PLATFORM_IDENTITY_ACCOUNT_DISABLED(ErrorKind.FORBIDDEN),
    PLATFORM_IDENTITY_EMPLOYEE_SEPARATED(ErrorKind.FORBIDDEN),
    PLATFORM_IDENTITY_ROLE_NOT_ALLOWED(ErrorKind.FORBIDDEN),
    PLATFORM_IDENTITY_ROLE_NOT_FOUND(ErrorKind.NOT_FOUND),
    PLATFORM_IDENTITY_ROLE_INVALID_CODE(ErrorKind.UNPROCESSABLE),
    PLATFORM_IDENTITY_ROLE_BLANK_NAME(ErrorKind.UNPROCESSABLE),
    PLATFORM_IDENTITY_ROLE_RESERVED_CODE(ErrorKind.UNPROCESSABLE),
    PLATFORM_IDENTITY_ROLE_DUPLICATE_CODE(ErrorKind.CONFLICT),
    PLATFORM_IDENTITY_ROLE_DUPLICATE_NAME(ErrorKind.CONFLICT),
    PLATFORM_IDENTITY_ROLE_SYSTEM_FROZEN(ErrorKind.CONFLICT),
    PLATFORM_IDENTITY_ROLE_IN_USE(ErrorKind.CONFLICT),
    PLATFORM_IDENTITY_ROLE_CUSTOM_ORG_UNITS_INVALID(ErrorKind.INVALID),
    PLATFORM_IDENTITY_ROLE_SCOPE_NOT_ALLOWED(ErrorKind.UNPROCESSABLE),
    PLATFORM_IDENTITY_PERMISSION_UNKNOWN(ErrorKind.UNPROCESSABLE),
    PLATFORM_IDENTITY_PERMISSION_ADMINISTRATOR_MODE_ONLY(ErrorKind.UNPROCESSABLE),
    PLATFORM_IDENTITY_ACCOUNT_NOT_FOUND(ErrorKind.NOT_FOUND),
    PLATFORM_IDENTITY_ROLE_TRANSITION_ILLEGAL(ErrorKind.CONFLICT),
    PLATFORM_IDENTITY_ACCOUNT_TRANSITION_ILLEGAL(ErrorKind.CONFLICT),
    PLATFORM_IDENTITY_CONCURRENT_UPDATE(ErrorKind.CONFLICT),
    PLATFORM_IDENTITY_DEFAULT_ROLE_MISSING(ErrorKind.UNAVAILABLE),
    PLATFORM_IDENTITY_NOT_SIGNED_IN(ErrorKind.UNAUTHENTICATED),
    PLATFORM_IDENTITY_LOGIN_RATE_LIMITED(ErrorKind.TOO_MANY_REQUESTS),
    PLATFORM_IDENTITY_EMERGENCY_ADMIN_TRANSITION_ILLEGAL(ErrorKind.CONFLICT),
    PLATFORM_IDENTITY_EMERGENCY_ADMIN_NOT_FOUND(ErrorKind.NOT_FOUND),
    PLATFORM_IDENTITY_EMERGENCY_ADMIN_DUPLICATE(ErrorKind.CONFLICT),
    PLATFORM_IDENTITY_EMERGENCY_BINDING_INVALID(ErrorKind.UNPROCESSABLE),
    PLATFORM_IDENTITY_OPERATION_WITNESS_REQUIRED(ErrorKind.UNPROCESSABLE),
    PLATFORM_IDENTITY_ADMINISTRATOR_MODE_DENIED(ErrorKind.FORBIDDEN),
    PLATFORM_IDENTITY_FORCED_LOGOUT_SELF_FORBIDDEN(ErrorKind.FORBIDDEN),
    PLATFORM_IDENTITY_FORCED_LOGOUT_REASON_REQUIRED(ErrorKind.UNPROCESSABLE),
    PLATFORM_IDENTITY_OWN_ROLES_FORBIDDEN(ErrorKind.FORBIDDEN),
    PLATFORM_IDENTITY_OWN_ROLE_DEFINITION_FORBIDDEN(ErrorKind.FORBIDDEN),
    PLATFORM_IDENTITY_AUTHORIZATION_REQUEST_NOT_FOUND(ErrorKind.NOT_FOUND),
    PLATFORM_IDENTITY_AUTHORIZATION_REQUEST_NOT_PENDING(ErrorKind.CONFLICT),
    PLATFORM_IDENTITY_AUTHORIZATION_CONFIRMER_NOT_ALLOWED(ErrorKind.FORBIDDEN),
    PLATFORM_IDENTITY_ACCESS_SCOPE_UNAVAILABLE(ErrorKind.FORBIDDEN),
    PLATFORM_IDENTITY_LAST_SUPER_ADMIN_PROTECTED(ErrorKind.UNPROCESSABLE);

    private final ErrorKind kind;

    IdentityError(ErrorKind kind) {
        this.kind = kind;
    }

    public ErrorKind kind() {
        return kind;
    }

    public DomainException refusal(String message) {
        return new DomainException(this, kind, message);
    }
}
