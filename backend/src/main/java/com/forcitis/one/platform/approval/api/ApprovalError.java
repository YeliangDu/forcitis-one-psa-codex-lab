package com.forcitis.one.platform.approval.api;

import com.forcitis.one.kernel.DomainException;
import com.forcitis.one.kernel.ErrorCode;
import com.forcitis.one.kernel.ErrorKind;

public enum ApprovalError implements ErrorCode {
    PLATFORM_APPROVAL_TASK_NOT_FOUND(ErrorKind.NOT_FOUND),
    PLATFORM_APPROVAL_TASK_ALREADY_CLAIMED(ErrorKind.CONFLICT),
    PLATFORM_APPROVAL_SHARE_ALREADY_TAKEN(ErrorKind.UNPROCESSABLE),
    PLATFORM_APPROVAL_DECISION_EMPTY(ErrorKind.INVALID),
    PLATFORM_APPROVAL_DECISION_DUPLICATE_TASK(ErrorKind.UNPROCESSABLE),
    PLATFORM_APPROVAL_DECISION_CROSS_INSTANCE(ErrorKind.UNPROCESSABLE),
    PLATFORM_APPROVAL_DECISION_SINGLE_ONLY(ErrorKind.UNPROCESSABLE),
    PLATFORM_APPROVAL_HOOK_BLOCKED(ErrorKind.CONFLICT),
    PLATFORM_APPROVAL_HOOK_NOT_REGISTERED(ErrorKind.CONFLICT),
    PLATFORM_APPROVAL_REQUEST_NOT_FOUND(ErrorKind.NOT_FOUND),
    PLATFORM_APPROVAL_NO_ROUTE(ErrorKind.UNPROCESSABLE),
    PLATFORM_APPROVAL_NO_PROCESS(ErrorKind.UNPROCESSABLE),
    PLATFORM_APPROVAL_DOCUMENT_TYPE_UNREGISTERED(ErrorKind.UNPROCESSABLE),
    PLATFORM_APPROVAL_ROUTING_FLAG_UNKNOWN(ErrorKind.UNPROCESSABLE),
    PLATFORM_APPROVAL_FORM_FIELD_UNKNOWN(ErrorKind.UNPROCESSABLE),
    PLATFORM_APPROVAL_ROUND_MISMATCH(ErrorKind.CONFLICT),
    PLATFORM_APPROVAL_ALREADY_APPROVED(ErrorKind.CONFLICT),
    PLATFORM_APPROVAL_CUTOFF_PASSED(ErrorKind.CONFLICT),
    PLATFORM_APPROVAL_NOT_INITIATOR(ErrorKind.FORBIDDEN),
    PLATFORM_APPROVAL_NOT_ADMINISTRATOR(ErrorKind.FORBIDDEN),
    PLATFORM_APPROVAL_TRANSFER_TARGET_INVALID(ErrorKind.UNPROCESSABLE),
    PLATFORM_APPROVAL_ASSIGNEE_INPUT_INVALID(ErrorKind.UNPROCESSABLE),
    PLATFORM_APPROVAL_PAGE_INVALID(ErrorKind.INVALID),
    PLATFORM_APPROVAL_NODE_CONFIG_INVALID(ErrorKind.UNAVAILABLE),
    PLATFORM_APPROVAL_PROCESS_NOT_DEPLOYED(ErrorKind.UNAVAILABLE),
    PLATFORM_APPROVAL_NO_ASSIGNEE_FOUND(ErrorKind.UNPROCESSABLE),
    PLATFORM_APPROVAL_ESCALATION_TARGET_MISSING(ErrorKind.UNPROCESSABLE);

    private final ErrorKind kind;

    ApprovalError(ErrorKind kind) {
        this.kind = kind;
    }

    public DomainException refusal(String message) {
        return new DomainException(this, kind, message);
    }
}
