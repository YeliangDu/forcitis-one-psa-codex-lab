-- one-data Q-02 岗位与职级取证第 1 步（ADR-0037，取证账号，只看元数据，不读数据）：与岗位、职级相关的表与列名。两库各跑一次。
SELECT DB_NAME() AS database_name, t.TABLE_NAME, (SELECT SUM(p.rows) FROM sys.partitions p WHERE p.object_id = OBJECT_ID(QUOTENAME(t.TABLE_SCHEMA) + N'.' + QUOTENAME(t.TABLE_NAME)) AND p.index_id IN (0, 1)) AS row_count
  FROM INFORMATION_SCHEMA.TABLES t
 WHERE t.TABLE_TYPE = N'BASE TABLE' AND t.TABLE_SCHEMA = N'dbo' AND (
       LOWER(t.TABLE_NAME) LIKE N'%post%' OR LOWER(t.TABLE_NAME) LIKE N'%level%' OR LOWER(t.TABLE_NAME) LIKE N'%grade%' OR LOWER(t.TABLE_NAME) LIKE N'%job%'
    OR LOWER(t.TABLE_NAME) LIKE N'org\_relationship%' ESCAPE N'\' OR LOWER(t.TABLE_NAME) LIKE N'org\_role%' ESCAPE N'\' OR LOWER(t.TABLE_NAME) IN (N'org_member', N'formmain_0307'))
 ORDER BY t.TABLE_NAME;
GO
SELECT DB_NAME() AS database_name, c.TABLE_NAME, c.COLUMN_NAME, c.DATA_TYPE, c.CHARACTER_MAXIMUM_LENGTH
  FROM INFORMATION_SCHEMA.COLUMNS c
 WHERE c.TABLE_SCHEMA = N'dbo' AND (
       LOWER(c.COLUMN_NAME) LIKE N'%post%' OR LOWER(c.COLUMN_NAME) LIKE N'%level%' OR LOWER(c.COLUMN_NAME) LIKE N'%grade%' OR LOWER(c.COLUMN_NAME) LIKE N'%job%' OR c.COLUMN_NAME LIKE N'%职级%')
 ORDER BY c.TABLE_NAME, c.COLUMN_NAME;
GO
SELECT DB_NAME() AS database_name, c.TABLE_NAME, c.COLUMN_NAME, c.DATA_TYPE FROM INFORMATION_SCHEMA.COLUMNS c
 WHERE DB_NAME() = N'a8_db' AND c.TABLE_SCHEMA = N'dbo' AND c.TABLE_NAME IN (N'ORG_POST', N'ORG_RELATIONSHIP', N'ORG_ROLE', N'ORG_ROLE_POST', N'ORG_MEMBER_POST')
 ORDER BY c.TABLE_NAME, c.ORDINAL_POSITION;
GO
SELECT DB_NAME() AS database_name, c.TABLE_NAME, c.COLUMN_NAME, c.DATA_TYPE FROM INFORMATION_SCHEMA.COLUMNS c
 WHERE DB_NAME() = N'ruoyi-vue-pro' AND c.TABLE_SCHEMA = N'dbo' AND c.TABLE_NAME IN (N'system_post', N'system_user_post')
 ORDER BY c.TABLE_NAME, c.ORDINAL_POSITION;
GO
SELECT DB_NAME() AS database_name, c.TABLE_NAME, c.COLUMN_NAME, c.DATA_TYPE FROM INFORMATION_SCHEMA.COLUMNS c
 WHERE DB_NAME() = N'a8_db' AND c.TABLE_NAME = N'CAP_FORM_DEFINITION' ORDER BY c.ORDINAL_POSITION;
