-- 附件大小分位数取证 第二步（只出聚合，不取文件名、内容与标识）。one_evidence_ro（ADR-0037 第 7 项）。ClamAV 实施卡 OPS-1021-OPS-02 第 8 条。
SET LOCK_TIMEOUT 1000;

-- CTP_FILE.FILE_SIZE：全表大小分位数与阈值占比（只出聚合）
SELECT DISTINCT N'CTP_FILE.FILE_SIZE' AS source_name, COUNT_BIG(*) OVER () AS file_count,
       PERCENTILE_CONT(0.50) WITHIN GROUP (ORDER BY CAST(FILE_SIZE AS float)) OVER () / 1048576.0 AS p50_mb,
       PERCENTILE_CONT(0.90) WITHIN GROUP (ORDER BY CAST(FILE_SIZE AS float)) OVER () / 1048576.0 AS p90_mb,
       PERCENTILE_CONT(0.95) WITHIN GROUP (ORDER BY CAST(FILE_SIZE AS float)) OVER () / 1048576.0 AS p95_mb,
       PERCENTILE_CONT(0.99) WITHIN GROUP (ORDER BY CAST(FILE_SIZE AS float)) OVER () / 1048576.0 AS p99_mb,
       PERCENTILE_CONT(0.999) WITHIN GROUP (ORDER BY CAST(FILE_SIZE AS float)) OVER () / 1048576.0 AS p999_mb,
       MAX(CAST(FILE_SIZE AS float)) OVER () / 1048576.0 AS max_mb,
       SUM(CASE WHEN FILE_SIZE > 25 * 1048576 THEN 1 ELSE 0 END) OVER () AS over_25mb,
       SUM(CASE WHEN FILE_SIZE > 100 * 1048576 THEN 1 ELSE 0 END) OVER () AS over_100mb,
       SUM(CAST(FILE_SIZE AS float)) OVER () / 1073741824.0 AS total_gb
  FROM [a8_db].dbo.CTP_FILE
 WHERE DB_NAME() = N'a8_db' AND FILE_SIZE IS NOT NULL AND FILE_SIZE >= 0 OPTION (MAXDOP 1);

-- CTP_ATTACHMENT.ATTACHMENT_SIZE：全表大小分位数与阈值占比（只出聚合）
SELECT DISTINCT N'CTP_ATTACHMENT.ATTACHMENT_SIZE' AS source_name, COUNT_BIG(*) OVER () AS file_count,
       PERCENTILE_CONT(0.50) WITHIN GROUP (ORDER BY CAST(ATTACHMENT_SIZE AS float)) OVER () / 1048576.0 AS p50_mb,
       PERCENTILE_CONT(0.90) WITHIN GROUP (ORDER BY CAST(ATTACHMENT_SIZE AS float)) OVER () / 1048576.0 AS p90_mb,
       PERCENTILE_CONT(0.95) WITHIN GROUP (ORDER BY CAST(ATTACHMENT_SIZE AS float)) OVER () / 1048576.0 AS p95_mb,
       PERCENTILE_CONT(0.99) WITHIN GROUP (ORDER BY CAST(ATTACHMENT_SIZE AS float)) OVER () / 1048576.0 AS p99_mb,
       PERCENTILE_CONT(0.999) WITHIN GROUP (ORDER BY CAST(ATTACHMENT_SIZE AS float)) OVER () / 1048576.0 AS p999_mb,
       MAX(CAST(ATTACHMENT_SIZE AS float)) OVER () / 1048576.0 AS max_mb,
       SUM(CASE WHEN ATTACHMENT_SIZE > 25 * 1048576 THEN 1 ELSE 0 END) OVER () AS over_25mb,
       SUM(CASE WHEN ATTACHMENT_SIZE > 100 * 1048576 THEN 1 ELSE 0 END) OVER () AS over_100mb,
       SUM(CAST(ATTACHMENT_SIZE AS float)) OVER () / 1073741824.0 AS total_gb
  FROM [a8_db].dbo.CTP_ATTACHMENT
 WHERE DB_NAME() = N'a8_db' AND ATTACHMENT_SIZE IS NOT NULL AND ATTACHMENT_SIZE >= 0 OPTION (MAXDOP 1);

-- 按 MIME 类型的文件数与 P99 大小（取文件数前 12 的类型）
WITH x AS (SELECT MIME_TYPE, CAST(FILE_SIZE AS float) AS sz FROM [a8_db].dbo.CTP_FILE WHERE DB_NAME() = N'a8_db' AND FILE_SIZE IS NOT NULL AND FILE_SIZE >= 0),
     g AS (SELECT DISTINCT MIME_TYPE, COUNT_BIG(*) OVER (PARTITION BY MIME_TYPE) AS n,
                  PERCENTILE_CONT(0.99) WITHIN GROUP (ORDER BY sz) OVER (PARTITION BY MIME_TYPE) / 1048576.0 AS p99_mb,
                  MAX(sz) OVER (PARTITION BY MIME_TYPE) / 1048576.0 AS max_mb FROM x)
SELECT TOP (12) MIME_TYPE, n AS file_count, p99_mb, max_mb FROM g ORDER BY n DESC OPTION (MAXDOP 1);
