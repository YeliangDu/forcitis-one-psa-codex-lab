-- B31P Q04-A 第一步：按已知模板 id 的 COL_SUMMARY 总行数（走 IDX_templete_id 的索引扫描，不回表），用来决定窗口计数的代价。只出计数，不含实例标识。one_evidence_ro（ADR-0037 第 7 项）。
SET LOCK_TIMEOUT 1000;
SELECT s.TEMPLETE_ID AS template_id, COUNT_BIG(*) AS total_rows
  FROM [a8_db].dbo.COL_SUMMARY AS s WITH (INDEX(IDX_templete_id))
 WHERE DB_NAME() = N'a8_db' AND s.TEMPLETE_ID IN (-803037765431705053, 16074125293700, 16486247748910, 16620851075370, 2916490644621970991, 5324409057402766767, 5779151688961574431, 6389177723207763537, 7187395059800230659, 8339262726610963687, 9068384877204753833)
 GROUP BY s.TEMPLETE_ID ORDER BY s.TEMPLETE_ID OPTION (MAXDOP 1);
