-- ADR-0037 第 5 项第 4 条 · 取证账号在 [ruoyi-vue-pro] 的用户：与运行时账号同形（库级只读、库级 DENY 写 / DDL / EXECUTE / REFERENCES 、不入角色）
SET XACT_ABORT ON;
BEGIN TRANSACTION;
CREATE USER [one_evidence_ro] FOR LOGIN [one_evidence_ro] WITH DEFAULT_SCHEMA = dbo;
GRANT SELECT ON DATABASE::[ruoyi-vue-pro] TO [one_evidence_ro];
DENY INSERT, UPDATE, DELETE, ALTER, EXECUTE, REFERENCES, CREATE TABLE, CREATE VIEW, CREATE PROCEDURE, CREATE FUNCTION, CREATE SCHEMA
  ON DATABASE::[ruoyi-vue-pro] TO [one_evidence_ro];
COMMIT TRANSACTION;
GO
