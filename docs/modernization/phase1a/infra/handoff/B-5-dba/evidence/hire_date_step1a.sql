-- 入职日期口径取证 a8_db 部分（单独跑）
SET LOCK_TIMEOUT 1000;
IF DB_NAME() = N'a8_db'
BEGIN
-- ① HR_STAFF_INFO 全部列
SELECT c.COLUMN_NAME AS column_name, c.DATA_TYPE AS data_type FROM INFORMATION_SCHEMA.COLUMNS AS c WHERE c.TABLE_SCHEMA = N'dbo' AND c.TABLE_NAME = N'HR_STAFF_INFO' ORDER BY c.ORDINAL_POSITION;
-- 日期型列：非空个数、最早、最晚
SELECT N'WORK_STARTING_DATE' AS col, COUNT(WORK_STARTING_DATE) AS non_null, MIN(WORK_STARTING_DATE) AS min_value, MAX(WORK_STARTING_DATE) AS max_value FROM dbo.HR_STAFF_INFO
UNION ALL SELECT N'BEGIN_WORK_DATE', COUNT(BEGIN_WORK_DATE), MIN(BEGIN_WORK_DATE), MAX(BEGIN_WORK_DATE) FROM dbo.HR_STAFF_INFO
UNION ALL SELECT N'IMAGE_DATETIME', COUNT(IMAGE_DATETIME), MIN(IMAGE_DATETIME), MAX(IMAGE_DATETIME) FROM dbo.HR_STAFF_INFO;
-- ② ORG_MEMBER.CREATE_TIME
SELECT COUNT(CREATE_TIME) AS non_null, MIN(CREATE_TIME) AS min_value, MAX(CREATE_TIME) AS max_value FROM dbo.ORG_MEMBER;
SELECT YEAR(CREATE_TIME) AS create_year, COUNT(*) AS active_members FROM dbo.ORG_MEMBER WHERE IS_DELETED = 0 AND IS_ENABLE = 1 GROUP BY YEAR(CREATE_TIME) ORDER BY create_year;
END
